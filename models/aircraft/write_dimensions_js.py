"""Copy the numbers the app's flight code needs from spec.py into src/flight/aircraft/dimensions.js (plan 03, F3.6).

spec.py is the one source of the aircraft's dimensions. The app cannot import Python, so this script writes the
numbers it needs (the fuselage section, the wing planform, the window stations and blanks, the cabin and the seat
layout) into the block between the GENERATED markers of dimensions.js, as a frozen object literal named SPEC. The
rest of dimensions.js derives its exports from SPEC. tests/python/flight/test_aircraft_cabin.py runs this with
--check and fails when the two have drifted.

    python3 models/aircraft/write_dimensions_js.py            # rewrite the block
    python3 models/aircraft/write_dimensions_js.py --check    # exit 1 if the block is not what spec.py gives

Pure standard library (spec.py is too), so it runs under any Python 3.10+.
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
TARGET = ROOT / "src" / "flight" / "aircraft" / "dimensions.js"
BEGIN = "// BEGIN GENERATED by models/aircraft/write_dimensions_js.py from models/aircraft/spec.py: do not edit"
END = "// END GENERATED"


def load_spec():
    loader = importlib.util.spec_from_file_location("aircraft_spec_for_js", HERE / "spec.py")
    module = importlib.util.module_from_spec(loader)
    sys.modules[loader.name] = module  # dataclasses look their module up while the class is defined
    loader.loader.exec_module(module)
    return module


def r(v, nd=4):
    """Numbers rounded to 0.1 mm (stations, sizes); tuples become lists."""
    if isinstance(v, (list, tuple)):
        return [r(x, nd) for x in v]
    if isinstance(v, bool):
        return v
    if isinstance(v, int):
        return v
    return round(float(v), nd)


def spec_numbers(S) -> dict:
    F = S.FUSELAGE
    W = S.WING
    win = S.WINDOWS
    C = S.CABIN
    v = lambda d: d.value  # noqa: E731
    return {
        "frame": "body axes: heights above the main-gear contact plane, fuselage datum level; stations aft of the nose",
        "fuselage": {
            "length": r(v(S.LENGTH_FUSELAGE)), "lengthOverall": r(v(S.LENGTH_OVERALL)),
            "width": r(v(F["width"])), "halfWidth": r(v(F["half_width"])), "height": r(v(F["height"])),
            "cabinWidth": r(v(F["cabin_width"])), "floorZ": r(v(F["floor_z"])), "topZ": r(v(F["top_z"])),
            "floorToCeiling": r(v(F["floor_to_ceiling"])),
        },
        "gear": {"noseStation": r(v(S.GEAR["nose_station"])), "wheelbase": r(v(S.GEAR["wheelbase"])),
                 "track": r(v(S.GEAR["track"])), "mainStation": r(v(S.STATIONS["main_gear"]))},
        "groundAttitudeDeg": r(v(S.GROUND_ATTITUDE), 5),
        "wing": {
            "spanBare": r(v(S.SPAN_BARE)), "spanWinglets": r(v(S.SPAN_WINGLETS)), "area": r(v(W["area"])),
            "sweepQuarter": r(v(W["sweep_quarter_chord"])), "dihedral": r(v(W["dihedral"])),
            "rootY": r(v(W["root_y"])), "le": r(v(W["le"])), "te": r(v(W["te"])), "tipLE": r(v(W["tip_le"])),
        },
        "overwingExits": r(v(S.DOORS["overwing_exits"]["station"])),
        "windows": {
            "width": r(v(win["opening"])[0]), "height": r(v(win["opening"])[1]),
            "cornerRadius": r(v(win["corner_radius"])), "centreAboveFloor": r(v(win["centre_above_floor"])),
            "right": r(v(win["right"])), "left": r(v(win["left"])),
            "blanksRight": r(v(win["blanks_right"])), "blanksLeft": r(v(win["blanks_left"])),
        },
        "cabin": {
            "trimRadius": r(v(C["trim_radius"])), "trimWidestAboveFloor": r(v(C["trim_widest_above_floor"])),
            "dadoInset": r(v(C["dado_inset"])), "binLipAboveFloor": r(v(C["bin_lip_above_floor"])),
            "binOutboardAboveFloor": r(v(C["bin_outboard_above_floor"])), "binClearance": r(v(C["bin_clearance"])),
            "ceilingAboveFloor": r(v(C["ceiling_above_floor"])), "revealFlare": r(v(C["reveal_flare"])),
            "frameWidth": r(v(C["frame_width"])), "frameRelief": r(v(C["frame_relief"])),
            "innerPaneInset": r(v(C["inner_pane_inset"])), "paneSpacing": r(v(C["pane_spacing"])),
            "shadeTravel": r(v(C["shade_travel"])), "panelHalfLength": r(v(C["panel_half_length"])),
            "rows": r(v(C["rows"])), "pitch": r(v(C["pitch"])), "exitPitch": r(v(C["exit_pitch"])),
            "exitRows": r(v(C["exit_rows"])), "firstRowFront": r(v(C["first_row_front"])),
            "seatWidth": r(v(C["seat_width"])), "tripleWidth": r(v(C["triple_width"])), "aisle": r(v(C["aisle"])),
            "cushionTop": r(v(C["cushion_top"])), "armrestTop": r(v(C["armrest_top"])),
            "backTop": r(v(C["back_top"])), "backThickness": r(v(C["back_thickness"])),
            "cushionDepth": r(v(C["cushion_depth"])), "backFace": r(v(C["back_face"])),
            "eyeAft": r(v(C["eye_aft"])), "eyeAboveFloor": r(v(C["eye_above_floor"])),
            "traySize": r(v(C["tray_size"])), "bulkheadAhead": r(v(C["bulkhead_ahead"])),
        },
        "estimated": sorted(f"{k}" for k, d in {**{f"windows.{k}": d for k, d in win.items()},
                                                   **{f"cabin.{k}": d for k, d in C.items()}}.items()
                            if d.source == S.ESTIMATED),
    }


def dump(value, indent=0) -> str:
    """JSON with every list of numbers (and every list of such lists) kept on one line."""
    pad, inner = "  " * indent, "  " * (indent + 1)
    if isinstance(value, dict):
        items = [f"{inner}{json.dumps(k)}: {dump(v, indent + 1)}" for k, v in value.items()]
        return "{\n" + ",\n".join(items) + f"\n{pad}}}"
    if isinstance(value, list) and all(not isinstance(v, (dict, str)) for v in value):
        return json.dumps(value, separators=(", ", ": "))
    if isinstance(value, list):
        return "[\n" + ",\n".join(f"{inner}{dump(v, indent + 1)}" for v in value) + f"\n{pad}]"
    return json.dumps(value, ensure_ascii=False)


def block(S) -> str:
    return f"{BEGIN}\nexport const SPEC = deepFreeze({dump(spec_numbers(S))});\n{END}"


def main(argv: list[str]) -> int:
    S = load_spec()
    src = TARGET.read_text(encoding="utf-8")
    if BEGIN not in src or END not in src:
        print(f"{TARGET}: no GENERATED markers", file=sys.stderr)
        return 2
    a = src.index(BEGIN)
    b = src.index(END) + len(END)
    new = src[:a] + block(S) + src[b:]
    if "--check" in argv:
        if new != src:
            print(f"{TARGET.relative_to(ROOT)} has drifted from spec.py: run models/aircraft/write_dimensions_js.py",
                  file=sys.stderr)
            return 1
        print("dimensions.js matches spec.py")
        return 0
    if new != src:
        TARGET.write_text(new, encoding="utf-8")
        print(f"wrote {TARGET.relative_to(ROOT)}")
    else:
        print("dimensions.js already matches spec.py")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
